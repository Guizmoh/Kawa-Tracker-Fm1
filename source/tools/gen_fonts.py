"""KAWA's other screen fonts (OPTIONS, KNOB 4): firmware/gen/kawa_fonts.h, from the fonts in assets/fonts/.

  python3 tools/gen_fonts.py        (needs Pillow with FreeType)

Each font in the layout of FONT_S and FONT_L (felucca_font.h, Terminus): a small one, 8 x 16 a character (the
bitmap 12 wide from 2 left of the pen), and a large one, 16 x 32 (24 wide from 4 left), 4 bits a pixel. The
capitals stand where Terminus's do (rows 2..11 of the small cell, 4..23 of the large one): every screen of
KAWA is laid out on them (T_CROP draws rows 2..13). The large one keeps only what KAWA writes large (the tempo,
the root of the scale, KAWA); the rest of it shows as '?' (g_text_l: kawa_ui.c, three places).

  DOUCE   from IBM Plex Mono SemiBold (SIL OFL 1.1), smoothed (rendered 8 x larger, then averaged)
  CLAIRE  from Atkinson Hyperlegible Mono (SIL OFL 1.1), smoothed, weight 600 (700 large)
  8-BIT   from Press Start 2P (SIL OFL 1.1), at its own pixel size, no smoothing
Under the OFL these are Modified Versions: they do not carry the Reserved Font Names ("Plex", "Press Start 2P");
the licences are in assets/fonts/."""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets" / "fonts"
LARGE = " #-0123456789?ABCDEFGKW"   # what KAWA writes in FONT_L: the tempo, the root of the scale, KAWA

# (name in the code, file, how, weight small, weight large)
SPECS = [
    ("DOUCE", "IBMPlexMono-SemiBold.ttf", "smooth", None, None),
    ("CLAIRE", "AtkinsonHyperlegibleMono.ttf", "smooth", 600, 700),
    ("8BIT", "PressStart2P-Regular.ttf", "pixel", None, None),
]


def font_at(path, size, weight):
    f = ImageFont.truetype(str(path), size)
    if weight is not None:
        f.set_variation_by_axes([weight])
    return f


def render_smooth(path, ch, cw, ch_h, pad, base, cap, weight, ss=8):
    """a glyph anti-aliased: capitals cap pixels tall, their foot on row base, centred in a cell cw wide"""
    probe = font_at(path, 100 * ss, weight)
    hb = probe.getbbox("H")
    size = int(round(100 * ss * cap * ss / (hb[3] - hb[1])))   # capitals cap x ss pixels tall at size ss
    f = font_at(path, size, weight)
    hb = f.getbbox("H")
    w = cw + 2 * pad
    im = Image.new("L", (w * ss, ch_h * ss), 0)
    d = ImageDraw.Draw(im)
    d.text((pad * ss + (cw * ss - f.getlength("M")) / 2, (base + 1) * ss - hb[3]), ch, font=f, fill=255)
    sm = im.resize((w, ch_h), Image.BOX)
    return [[min(15, (sm.getpixel((x, y)) + 8) // 17) for x in range(w)] for y in range(ch_h)]


def render_pixel(path, ch, cw, ch_h, pad, base, size):
    """a pixel font at its own size, on and off only"""
    f = font_at(path, size, None)
    hb = f.getbbox("H")
    w = cw + 2 * pad
    im = Image.new("L", (w, ch_h), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((pad + (cw - int(f.getlength("M"))) // 2, base + 1 - hb[3]), ch, font=f, fill=255)
    return [[15 if im.getpixel((x, y)) > 127 else 0 for x in range(w)] for y in range(ch_h)]


def pack(g):
    """4 bits a pixel, the even column in the high nibble (kawa_gfx.c g_text)"""
    out = []
    for row in g:
        for x in range(0, len(row), 2):
            out.append(row[x] << 4 | (row[x + 1] if x + 1 < len(row) else 0))
    return out


def table(name, first, last, adv, bw, h, pad, glyphs, keep):
    """a felucca_font_t: identical glyphs share their bytes; one not kept is '?'"""
    data, off, seen = [], [], {}
    q = pack(glyphs["?"])
    for c in range(first, last + 1):
        b = pack(glyphs[chr(c)]) if chr(c) in keep else q
        k = bytes(b)
        if k not in seen:
            seen[k] = len(data)
            data += b
        off.append(seen[k])
    n = last - first + 1
    lines = [f"static const uint8_t {name}_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const uint16_t {name}_OFF[{n}] = {{{', '.join(map(str, off))}}};")
    lines.append(f"static const uint8_t {name}_ADV[{n}] = {{{', '.join([str(adv)] * n)}}};")
    lines.append(f"static const uint8_t {name}_BW[{n}] = {{{', '.join([str(bw)] * n)}}};")
    lines.append(f"static const felucca_font_t {name} = {{ {h}, {pad}, {first}, {last}, {name}_ADV, {name}_BW, {name}_OFF, "
                 f"{name}_DATA }};")
    return "\n".join(lines), len(data)


def main():
    out = ["/* generated by tools/gen_fonts.py from assets/fonts/ (SIL OFL 1.1: the licences are there): KAWA's other",
           " * screen fonts, in the layout of FONT_S and FONT_L. Do not edit. */", "#pragma once", ""]
    total = 0
    for name, file, how, w_s, w_l in SPECS:
        path = FONTS / file
        small, large = {}, {}
        for c in range(32, 127):
            ch = chr(c)
            if how == "smooth":
                small[ch] = render_smooth(path, ch, 8, 16, 2, 11, 10, w_s)
            else:
                small[ch] = render_pixel(path, ch, 8, 16, 2, 11, 8)
        for ch in LARGE:
            if how == "smooth":
                large[ch] = render_smooth(path, ch, 16, 32, 4, 23, 20, w_l)
            else:
                large[ch] = render_pixel(path, ch, 16, 32, 4, 23, 16)
        s, ns = table(f"FONT_S_{name}", 32, 126, 8, 12, 16, 2, small, set(small))
        l, nl = table(f"FONT_L_{name}", 32, 95, 16, 24, 32, 4, large, set(LARGE))
        out += [f"/* {name}: {file} */", s, l, ""]
        total += ns + nl
        print(f"{name}: small {ns} B, large {nl} B")
    (ROOT / "firmware" / "gen" / "kawa_fonts.h").write_text("\n".join(out))
    print(f"firmware/gen/kawa_fonts.h: {total} B of fonts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
