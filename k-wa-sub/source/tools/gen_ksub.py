"""K-WA SUB: the fixed-point tables and the screen fonts.

    python3 tools/gen_ksub.py      -> firmware/gen/ksub_tables.h, firmware/gen/ksub_fonts.h

Needs numpy and Pillow (the fonts are DejaVu Sans Bold, rendered with 16 grey levels)."""
import math
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "firmware" / "gen"
FS = 44100.0
CB = 16                      # samples per control block (ksub_dsp.c: KS_CB)
WT_N, WT_FR, WT_TABLES = 256, 8, 8
MIPS = (64, 12)              # harmonics kept per mip (mip 1 above ~F4)


def arr(ctype, name, vals, per=16):
    vals = list(vals)
    lines = [", ".join(str(int(v)) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def q15(x):
    return int(max(-32767, min(32767, round(x * 32767))))


# ---------------------------------------------------------------- wavetables
def bandlimit(wave, harms):
    """a cycle (any length) -> WT_N samples with only the first `harms` harmonics, peak 1"""
    spec = np.fft.rfft(wave)
    spec[harms + 1:] = 0
    spec[0] = 0
    out = np.fft.irfft(spec, len(wave))
    out = np.interp(np.arange(WT_N) * len(wave) / WT_N, np.arange(len(wave)), out)
    pk = np.max(np.abs(out))
    return out / pk if pk > 1e-9 else out


def additive(amps, phases=None):
    t = np.arange(4096) / 4096.0
    w = np.zeros(4096)
    for k, a in enumerate(amps, 1):
        if a:
            w += a * np.sin(2 * np.pi * k * t + (phases[k - 1] if phases else 0))
    return w


def formant_amps(freqs, gains, f0=110.0, bw=90.0, n=64):
    return [sum(g * math.exp(-((k * f0 - f) / bw) ** 2) for f, g in zip(freqs, gains)) + 0.02 / k for k in range(1, n + 1)]


VOWELS = {"A": ((800, 1150, 2900), (1, .5, .25)), "E": ((400, 1600, 2700), (1, .4, .2)),
          "I": ((250, 1750, 2600), (1, .3, .2)), "O": ((450, 800, 2830), (1, .45, .1)),
          "U": ((325, 700, 2530), (1, .25, .08))}


def table_frames(tb):
    t = np.arange(4096) / 4096.0
    fr = []
    for f in range(WT_FR):
        x = f / (WT_FR - 1)
        if tb == 0:      # BASIC: sine, triangle, saw, square, thin pulse
            seg = x * 4
            shapes = [np.sin(2 * np.pi * t), 1 - 4 * np.abs(t - 0.5) - 0 * t, 2 * t - 1, np.where(t < .5, 1.0, -1.0),
                      np.where(t < .12, 1.0, -0.14)]
            i = min(int(seg), 3)
            k = seg - i
            w = shapes[i] * (1 - k) + shapes[i + 1] * k
        elif tb == 1:    # HARMONIC: from the sine to every harmonic, brighter and brighter
            n = 1 + int(x * x * 40)
            w = additive([1.0 / k ** (1.2 - x * .7) if k <= n else 0 for k in range(1, 64)])
        elif tb == 2:    # GROWL: a formant peak walking up the harmonics, with a body under it
            c = 3 + x * 26
            w = additive([(1.0 / k) * .6 + math.exp(-((k - c) / (2 + x * 3)) ** 2) for k in range(1, 64)])
        elif tb == 3:    # VOCAL: U O A E I
            seq = "UOAEI"
            p = x * 4
            i = min(int(p), 3)
            k = p - i
            a0 = formant_amps(*VOWELS[seq[i]])
            a1 = formant_amps(*VOWELS[seq[i + 1]])
            w = additive([u * (1 - k) + v * k for u, v in zip(a0, a1)])
        elif tb == 4:    # FM: a 2:1 FM sweep of the index
            w = np.sin(2 * np.pi * t + x * 6 * np.sin(2 * np.pi * 2 * t))
        elif tb == 5:    # PWM: 50 % down to 4 %
            pw = .5 - x * .46
            w = np.where(t < pw, 1.0, -1.0)
        elif tb == 6:    # DIGITAL: a sine crushed to fewer and fewer levels, odd harmonics on top
            lv = max(2, int(16 - x * 14))
            s = np.sin(2 * np.pi * t) + x * .5 * np.sin(2 * np.pi * 3 * t) + x * .3 * np.sin(2 * np.pi * 7 * t)
            w = np.round(s * lv / 2) / lv * 2
        else:            # SYNC: a saw hard-synced from 1x to 6x
            r = 1 + x * 5
            w = 2 * ((t * r) % 1.0) - 1
        fr.append(w - np.mean(w))
    return fr


TABLE_NAMES = ["BASIC", "HARMONIC", "GROWL", "VOCAL", "FM", "PWM", "DIGITAL", "SYNC"]


def gen_tables():
    o = ["/* K-WA SUB: generated by tools/gen_ksub.py -- do not edit */\n#pragma once\n#include <stdint.h>\n"]
    o.append(arr("int16_t", "KS_SIN", [q15(math.sin(2 * math.pi * i / 1024)) for i in range(1025)]))
    # phase increment per sample, the top octave (notes 120 .. 132) in 1/64 semitone
    o.append(arr("uint32_t", "KS_PITCH", [round(440 * 2 ** ((120 + i / 64 - 69) / 12) / FS * 2 ** 32) for i in range(768)], 8))
    # the cutoff scale: x = 0..256 -> 20 Hz .. 19 kHz (log). One-pole g (Q16), Hz
    hz = [20 * (950 ** (i / 256)) for i in range(257)]
    o.append(arr("uint16_t", "KS_CUT_G", [min(65535, round((1 - math.exp(-2 * math.pi * min(f, 18000) / FS)) * 65536)) for f in hz]))
    o.append(arr("uint16_t", "KS_CUT_HZ", [round(f) for f in hz]))
    # envelope times: 0..127 -> 0.5 ms .. 12 s; attack step per control block (Q30) and decay factor per block (Q24)
    tms = [0.5 * (24000 ** (i / 127)) for i in range(128)]
    o.append(arr("uint32_t", "KS_ENV_MS10", [round(t * 10) for t in tms], 8))
    o.append(arr("uint32_t", "KS_ENV_ATK", [min(2 ** 30, round(2 ** 30 * CB / (t / 1000 * FS))) for t in tms], 8))
    o.append(arr("uint32_t", "KS_ENV_DEC", [round(math.exp(-CB * math.log(1000) / (t / 1000 * FS)) * 2 ** 24) for t in tms], 8))
    # free LFO: 0..127 -> 0.02 .. 40 Hz, phase step per control block; Hz x 100 for the screen
    lf = [0.02 * (2000 ** (i / 127)) for i in range(128)]
    o.append(arr("uint32_t", "KS_LFO_INC", [round(f * CB / FS * 2 ** 32) for f in lf], 8))
    o.append(arr("uint32_t", "KS_LFO_HZ100", [round(f * 100) for f in lf], 8))
    # wavetables: [mip][table][frame][sample]
    data = []
    for h in MIPS:
        for tb in range(WT_TABLES):
            for w in table_frames(tb):
                data += [q15(v * .97) for v in bandlimit(w, h)]
    o.append(arr("int16_t", "KS_WT", data))
    return "\n".join(o)


# ---------------------------------------------------------------- fonts
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZES = [("XS", 8, 126), ("S", 9, 126), ("M", 11, 126), ("B", 16, 126), ("L", 21, 95)]


def gen_fonts():
    o = ["/* K-WA SUB: generated by tools/gen_ksub.py from DejaVu Sans Bold (Bitstream Vera licence) -- do not edit */\n"
         "#pragma once\n#include <stdint.h>\n"
         "typedef struct { uint8_t h, first, last; const uint8_t *adv; const uint16_t *off; const uint8_t *data; } ks_font_t;\n"]
    for nm, sz, last in SIZES:
        f = ImageFont.truetype(FONT, sz)
        asc, desc = f.getmetrics()
        cap = f.getbbox("H")[1]          # the empty rows above the capitals are cut
        h = asc + desc - cap
        advs, offs, data = [], [], []
        for c in range(32, last + 2):
            ch = "·" if c == last + 1 else chr(c)   # the last glyph is the middle dot
            adv = max(1, round(f.getlength(ch)))
            im = Image.new("L", (adv + 2, asc + desc), 0)
            ImageDraw.Draw(im).text((0, 0), ch, font=f, fill=255)
            px = np.array(im)[cap:cap + h, :adv]
            offs.append(len(data))
            for row in px:
                r = [min(15, (int(v) + 8) // 17) for v in row] + [0]
                data += [(r[i] << 4) | r[i + 1] for i in range(0, adv, 2)]
            advs.append(adv)
        o.append(arr("uint8_t", f"KF_{nm}_ADV", advs, 24))
        o.append(arr("uint16_t", f"KF_{nm}_OFF", offs, 16))
        o.append(arr("uint8_t", f"KF_{nm}_DATA", data, 24))
        o.append(f"static const ks_font_t F_{nm} = {{{h}, 32, {last + 1}, KF_{nm}_ADV, KF_{nm}_OFF, KF_{nm}_DATA}};\n")
    return "\n".join(o)


if __name__ == "__main__":
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "ksub_tables.h").write_text(gen_tables())
    (GEN / "ksub_fonts.h").write_text(gen_fonts())
    print("ksub_tables.h", (GEN / "ksub_tables.h").stat().st_size, "B; ksub_fonts.h", (GEN / "ksub_fonts.h").stat().st_size, "B")
