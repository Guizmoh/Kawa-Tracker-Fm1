"""KAWA's fixed-point tables (the chip has no FPU): firmware/gen/kawa_tables.h.

  python3 tools/gen_tables.py
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "firmware" / "gen" / "kawa_tables.h"
FS = 44100
CHUNK = 16
CH = FS / CHUNK                      # control rate (chunks per second)


def arr(name, typ, vals, per=12):
    suf = "u" if typ.startswith("uint32") else ""
    rows = [", ".join(f"{v}{suf}" for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {typ} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "};\n"


def q4(v):
    return max(0, min(15, int(round(v))))


def main():
    fine = [round(2 ** (k / 768) * 2 ** 30) for k in range(64)]
    tms = [0, 2, 5, 10, 20, 35, 50, 80, 120, 180, 250, 350, 500, 800, 1200, 2000]
    rate = [65536 if t == 0 else max(1, round(65536 / (t / 1000 * CH))) for t in tms]
    taus = [0.001 * (4000 ** (i / 63)) for i in range(64)]
    dk = [round(65536 * math.exp(-1 / (tau * CH))) for tau in taus]
    svf = [round(2 * math.sin(math.pi * min(440 * 2 ** ((n - 69) / 12), 10000) / FS) * 32768) for n in range(128)]
    ton = []
    for i in range(16):
        fc = 300 * (16000 / 300) ** (i / 14)
        ton.append(32767 if i == 15 else round((1 - math.exp(-2 * math.pi * fc / FS)) * 32767))
    w = [[15 - i if i < 16 else i - 16 for i in range(32)],                        # TRI, as the NES
         [i // 2 for i in range(32)],                                               # SCIE
         [q4(7.5 + 7.5 * math.sin(2 * math.pi * i / 32)) for i in range(32)],       # SINUS
         [q4(7.5 + 7.5 * max(-1, min(1, 2.2 * math.sin(2 * math.pi * i / 32)))) for i in range(32)],   # DOUX
         [0, 2, 4, 6, 8, 10, 12, 14, 15, 15, 15, 14, 14, 13, 13, 12, 11, 10, 8, 6, 4, 2, 1, 0, 0, 1, 1, 2, 2, 1, 0, 0]]
    for f in (lambda x: math.sin(x) + 0.5 * math.sin(2 * x) + 0.33 * math.sin(3 * x),   # ORGUE
              lambda x: 0.6 * math.sin(x) + 0.5 * math.sin(5 * x),                     # VOIX
              lambda x: math.sin(x + 2.2 * math.sin(2 * x))):                          # FM
        v = [f(2 * math.pi * i / 32) for i in range(32)]
        m = max(abs(a) for a in v)
        w.append([q4(7.5 + 7.5 * a / m) for a in v])
    pan = [(round(4096 * math.cos((p + 7) / 14 * math.pi / 2) * 1.414),
            round(4096 * math.sin((p + 7) / 14 * math.pi / 2) * 1.414)) for p in range(-7, 8)]
    out = ["/* generated by tools/gen_tables.py: KAWA's fixed-point tables",
           " * FINE      2^(k/768), Q30: 1/64 semitone steps",
           " * ENV_RATE  envelope step per control chunk (16 frames) for 0, 2, 5 .. 2000 ms, Q16",
           " * DECAY_K   exponential decay per chunk, tau 1 ms .. 4 s in 64 log steps, Q16",
           " * SVF_F     2 sin(pi fc / fs) of a state-variable filter per MIDI note (fc capped at 10 kHz), Q15",
           " * TON_A     one-pole low-pass coefficient for TON 0..15 (300 Hz .. open), Q15",
           " * WAVES     the ONDE tables: 32 steps of 4 bits (as a Game Boy wave channel)",
           " * PAN_G     equal-power pan, -7..+7, Q12 */",
           "#pragma once", "#include <stdint.h>",
           arr("FINE", "uint32_t", fine, 6), arr("ENV_RATE", "int32_t", rate, 16), arr("DECAY_K", "int32_t", dk, 16),
           arr("SVF_F", "int32_t", svf, 16), arr("TON_A", "int32_t", ton, 16),
           "static const uint8_t WAVES[8][32] = {\n" + ",\n".join("    {" + ", ".join(map(str, r)) + "}" for r in w) + "};\n",
           "static const int16_t PAN_G[15][2] = {" + ", ".join("{%d, %d}" % p for p in pan) + "};"] + fm6_tables()
    OUT.write_text("\n".join(out) + "\n")
    print("->", OUT)


